<?php

namespace Database\Seeders;

use App\Models\EmailConnection;
use App\Models\InvestmentAccount;
use App\Models\Platform;
use App\Models\Transaction;
use App\Models\User;
use Illuminate\Database\Seeder;
use Illuminate\Support\Facades\Hash;
use Carbon\Carbon;
use Exception;

class I104TestSeeder extends Seeder
{
    public function run(): void
    {
        // 1. Get or Create User
        $user = User::firstOrCreate(
            ['email' => 'test_i104@example.com'],
            ['name' => 'I104 Tester', 'password' => Hash::make('password')]
        );
        $this->command->info("User ready: {$user->email}");

        // 2. Create Platforms
        $stockbit = Platform::firstOrCreate(['code' => 'stockbit'], ['name' => 'Stockbit']);
        $pluang = Platform::firstOrCreate(['code' => 'pluang'], ['name' => 'Pluang']);
        $bions = Platform::firstOrCreate(['code' => 'bions'], ['name' => 'BIONS']);
        $this->command->info("Platforms ready.");

        // 3. Create Email Connections (User A -> Gmail 1, Gmail 2)
        $gmail1 = EmailConnection::firstOrCreate([
            'user_id' => $user->id,
            'email_address' => 'gmail1@example.com'
        ], [
            'oauth_provider' => 'google'
        ]);
        $gmail2 = EmailConnection::firstOrCreate([
            'user_id' => $user->id,
            'email_address' => 'gmail2@example.com'
        ], [
            'oauth_provider' => 'google'
        ]);
        $this->command->info("Email connections ready.");

        // 4. Create Investment Accounts
        // Gmail 1 -> Stockbit & BIONS
        $accStockbit = InvestmentAccount::firstOrCreate([
            'user_id' => $user->id,
            'platform_id' => $stockbit->id,
            'email_connection_id' => $gmail1->id,
        ], ['account_name' => 'My Stockbit']);
        
        $accBions = InvestmentAccount::firstOrCreate([
            'user_id' => $user->id,
            'platform_id' => $bions->id,
            'email_connection_id' => $gmail1->id,
        ], ['account_name' => 'My BIONS']);

        // Gmail 2 -> Pluang
        $accPluang = InvestmentAccount::firstOrCreate([
            'user_id' => $user->id,
            'platform_id' => $pluang->id,
            'email_connection_id' => $gmail2->id,
        ], ['account_name' => 'My Pluang Crypto']);
        
        $this->command->info("Investment accounts ready.");

        // 5. Create Transactions
        $this->createTransaction($accStockbit, 'BUY', 'BBCA', 100, 10000, 1000000, 'IDR');
        $this->createTransaction($accBions, 'SELL', 'GOTO', 500, 50, 25000, 'IDR');
        $this->createTransaction($accPluang, 'BUY', 'BTC', 0.005, 1000000000, 5000000, 'IDR');

        // 6. Test Deduplication (Transaction Hash)
        $this->command->info("Testing deduplication constraint...");
        try {
            $this->createTransaction($accStockbit, 'BUY', 'BBCA', 100, 10000, 1000000, 'IDR');
            $this->command->error("Deduplication FAILED! Duplicate transaction was inserted.");
        } catch (Exception $e) {
            $this->command->info("Deduplication SUCCESS! Duplicate transaction was rejected.");
        }

        $this->command->info("I1-04 Schema Test Completed Successfully!");
    }

    private function createTransaction($account, $type, $symbol, $qty, $price, $total, $currency)
    {
        $date = Carbon::now();
        // Simple hash logic for idempotency based on core fields
        $hashData = "{$account->id}|{$date->toDateString()}|{$type}|{$symbol}|{$qty}|{$price}|{$total}";
        $hash = md5($hashData);

        return Transaction::create([
            'investment_account_id' => $account->id,
            'transaction_date' => $date,
            'type' => $type,
            'symbol' => $symbol,
            'quantity' => $qty,
            'price' => $price,
            'total_amount' => $total,
            'currency' => $currency,
            'transaction_hash' => $hash,
            'source_metadata' => ['note' => 'Generated by I104TestSeeder']
        ]);
    }
}
