<?php

namespace Database\Seeders;

use Illuminate\Database\Console\Seeds\WithoutModelEvents;
use Illuminate\Database\Seeder;
use App\Models\User;
use App\Models\Platform;
use App\Models\EmailConnection;
use App\Models\InvestmentAccount;
use App\Models\Transaction;
use Illuminate\Support\Facades\Hash;
use Carbon\Carbon;

class MockTransactionSeeder extends Seeder
{
    /**
     * Run the database seeds.
     */
    public function run(): void
    {
        // 1. Setup Test User
        $user = User::firstOrCreate(
            ['email' => 'test@example.com'],
            ['name' => 'Test User', 'password' => Hash::make('password')]
        );
        $this->command->info("Test user verified: {$user->email}");

        // 2. Setup Platforms
        $stockbit = Platform::firstOrCreate(['code' => 'stockbit'], ['name' => 'Stockbit']);
        $bions = Platform::firstOrCreate(['code' => 'bions'], ['name' => 'BIONS']);
        $pluang = Platform::firstOrCreate(['code' => 'pluang'], ['name' => 'Pluang']);
        $this->command->info("Platforms verified.");

        // 3. Setup Email Connections
        $gmail1 = EmailConnection::firstOrCreate(
            ['user_id' => $user->id, 'email_address' => 'gmail1@example.com'],
            ['oauth_provider' => 'google']
        );
        $gmail2 = EmailConnection::firstOrCreate(
            ['user_id' => $user->id, 'email_address' => 'gmail2@example.com'],
            ['oauth_provider' => 'google']
        );
        $this->command->info("Email connections verified.");

        // 4. Setup Investment Accounts
        $accStockbit = InvestmentAccount::firstOrCreate(
            ['user_id' => $user->id, 'platform_id' => $stockbit->id, 'email_connection_id' => $gmail1->id],
            ['account_name' => 'Stockbit Saham']
        );
        $accBions = InvestmentAccount::firstOrCreate(
            ['user_id' => $user->id, 'platform_id' => $bions->id, 'email_connection_id' => $gmail1->id],
            ['account_name' => 'BIONS Saham']
        );
        $accPluang = InvestmentAccount::firstOrCreate(
            ['user_id' => $user->id, 'platform_id' => $pluang->id, 'email_connection_id' => $gmail2->id],
            ['account_name' => 'Pluang Crypto']
        );
        $this->command->info("Investment accounts verified.");

        // 5. Setup Transactions (Idempotent)
        $now = Carbon::now();

        // STOCKBIT Transactions (BBCA)
        $this->seedTransaction($accStockbit, $now->copy()->subDays(10), 'BUY', 'BBCA', 100, 9500, 950000, 'IDR');
        $this->seedTransaction($accStockbit, $now->copy()->subDays(5), 'BUY', 'BBCA', 50, 9600, 480000, 'IDR');
        $this->seedTransaction($accStockbit, $now->copy()->subDays(1), 'SELL', 'BBCA', 50, 10000, 500000, 'IDR');

        // BIONS Transactions (GOTO)
        $this->seedTransaction($accBions, $now->copy()->subDays(15), 'BUY', 'GOTO', 1000, 50, 50000, 'IDR');
        $this->seedTransaction($accBions, $now->copy()->subDays(2), 'SELL', 'GOTO', 500, 55, 27500, 'IDR');

        // PLUANG Transactions (BTC)
        $this->seedTransaction($accPluang, $now->copy()->subMonths(1), 'BUY', 'BTC', 0.05, 1000000000, 50000000, 'IDR');
        $this->seedTransaction($accPluang, $now->copy()->subDays(12), 'SELL', 'BTC', 0.01, 1100000000, 11000000, 'IDR');

        $this->command->info("Mock transactions seeded successfully!");
    }

    private function seedTransaction($account, $date, $type, $symbol, $qty, $price, $total, $currency)
    {
        // Calculate hash strictly like the controller does
        $hashData = implode('|', [
            $account->id,
            $date->toDateString(),
            $type,
            $symbol,
            (float) $qty,
            (float) $price,
            (float) $total
        ]);
        $hash = md5($hashData);

        Transaction::firstOrCreate(
            ['transaction_hash' => $hash],
            [
                'investment_account_id' => $account->id,
                'transaction_date' => $date,
                'type' => $type,
                'symbol' => $symbol,
                'quantity' => $qty,
                'price' => $price,
                'total_amount' => $total,
                'currency' => $currency,
                'source_metadata' => ['note' => 'Mock Data generated by MockTransactionSeeder']
            ]
        );
    }
}
